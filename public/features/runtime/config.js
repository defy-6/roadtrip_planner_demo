export function typeForTitle(title = '') {
  if (/航班|\b[A-Z]{2}\d{3,4}\b/i.test(title)) return 'flight';
  if (/午餐|晚餐|早餐|简餐/.test(title)) return 'food';
  if (/入住|休息|候机/.test(title)) return 'hotel';
  if (/抵达|下机|取行李|租车|验车|还车|起飞/.test(title)) return 'transport';
  if (/加油/.test(title)) return 'fuel';
  if (/服务区/.test(title)) return 'service';
  if (/驾驶|前往|返回|继续|返程|至/.test(title)) return 'drive';
  return 'spot';
}
